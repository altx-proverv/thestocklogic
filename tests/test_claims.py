#!/usr/bin/env python3
"""A DOC OR DOCSTRING MAY NOT CLAIM WHAT THE CODE DOES NOT DO (OPEN D-076).

Six times in two weeks a comment, header or doc said the opposite of its code:
06_push, universe.py's "auto-generated", config's "exited at market",
MERIDIAN's "NOTHING HERE IS BUILT", _complete_intent, radar/detect.py. Two
checks, both offline:

  (a) GENERATED FILES. Any tracked file that says it is generated / not to be
      edited must be registered in docs/claims.json with a generator that
      exists; "reproduce" outputs are rebuilt and diffed by their own test,
      "external" ones (need a live source) have their checkable parts checked.
  (b) STATUS CLAIMS. Any "not built / nothing calls / nothing reads / nothing
      imports / is never called" sentence, and any STATUS banner in docs/, must
      be registered with a check that is run here -- module exists, a crontab
      line runs it, a symbol has no callers outside the allowed files. A
      registered claim whose check fails is a failure; an unregistered claim is
      a failure.

Matching is on EXECUTABLE source for the code checks (comments and docstrings
stripped), so a sentence explaining the rule does not count as a caller.
"""
import ast
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from tests._srcutil import executable_source                    # noqa: E402

REG = json.loads((ROOT / "docs" / "claims.json").read_text())
failures = []


def check(label, got, want):
    ok = got == want
    if not ok:
        failures.append(f"{label}: got {got!r}, want {want!r}")
    print(f"  {label:<70} {str(got)[:20]:<22} {'ok' if ok else 'FAIL'}")


GEN_RE = re.compile(r"auto-?generated|generated by \S+\.py|do not edit (manually|by hand)|do not edit\.", re.I)
STATUS_RE = re.compile(r"NOT BUILT|NOTHING HERE IS BUILT|IS BUILT AND RUNNING|nothing (calls|imports|reads) (it|this)"
                       r"|is never called|no longer called|nothing reads it", re.I)
SKIP_PREFIX = ("tests/", "docs/OPEN.md", "docs/claims.json", "venv/", "migrations/")


def tracked(root: Path) -> list:
    try:
        out = subprocess.run(["git", "ls-files"], cwd=root, capture_output=True, text=True).stdout.split()
    except Exception:
        out = []
    if not out:                                        # a planted temp tree has no git
        out = [str(p.relative_to(root)) for p in root.rglob("*") if p.is_file()]
    return [f for f in out if f.endswith((".py", ".md", ".json", ".html", ".sh", ".box"))
            and not f.startswith(SKIP_PREFIX)]


def scan(root: Path, reg: dict) -> dict:
    gens = {g["generator"] for g in reg["generated"]}
    outs = {g["output"] for g in reg["generated"]}
    claims = reg["claims"]
    quotes = reg.get("quotes", [])
    unreg_gen, unreg_status = [], []
    for f in tracked(root):
        try:
            lines = (root / f).read_text(errors="replace").splitlines()
        except Exception:
            continue
        for i, line in enumerate(lines, 1):
            if any(q["where"] == f and q["text"] in line for q in quotes):
                continue                                   # a registered QUOTATION, not a claim
            if GEN_RE.search(line) and f not in gens and f not in outs:
                unreg_gen.append(f"{f}:{i}: {line.strip()[:90]}")
            m = STATUS_RE.search(line)
            if m and f.endswith((".py", ".md")):
                if not any(c["where"] == f and c["text"] in line for c in claims):
                    unreg_status.append(f"{f}:{i}: {line.strip()[:90]}")
    return {"generated": unreg_gen, "status": unreg_status}


# ── THE CHECKS A CLAIM CAN CARRY ──────────────────────────────────

def _py_files(root, scope):
    for d in scope:
        for p in (root / d).rglob("*.py"):
            yield p


def _exec(p):
    """Executable source of a file. A file that cannot be parsed is returned
    WHOLE rather than as "" -- an empty string would make every 'not called /
    not read' check pass on it, which is how this test first matched nothing."""
    try:
        return executable_source(p)
    except Exception:
        return p.read_text(errors="replace")


def run_check(root: Path, c: dict):
    """-> None if it holds, else the reason."""
    if "module_exists" in c:
        return None if (root / c["module_exists"]).exists() else f"{c['module_exists']} does not exist"
    if "cron" in c:
        cron = (root / "deploy" / "crontab.box").read_text()
        live = [l for l in cron.splitlines() if l.strip() and not l.lstrip().startswith("#")]
        return None if any(c["cron"] in l for l in live) else f"no crontab.box line runs {c['cron']!r}"
    if "not_cron" in c:
        cron = (root / "deploy" / "crontab.box").read_text()
        live = [l for l in cron.splitlines() if l.strip() and not l.lstrip().startswith("#")]
        hit = [l for l in live if c["not_cron"] in l]
        return None if not hit else f"a crontab.box line still runs {c['not_cron']!r}"
    if "called_only_in" in c:
        x = c["called_only_in"]
        bad = [str(p.relative_to(root)) for p in _py_files(root, x["scope"])
               if str(p.relative_to(root)) not in x["allowed"]
               and re.search(rf"\b{re.escape(x['symbol'])}\(", _exec(p))]
        return None if not bad else f"{x['symbol']}() is called from {bad}"
    if "not_read" in c:
        x = c["not_read"]
        bad = [str(p.relative_to(root)) for p in _py_files(root, x["scope"])
               if str(p.relative_to(root)) not in x["allowed"]
               and re.search(rf"\b{re.escape(x['name'])}\b", _exec(p))]
        return None if not bad else f"{x['name']} is read in {bad}"
    if "not_imported" in c:
        x = c["not_imported"]
        m = re.escape(x["module"])
        pat = re.compile(rf"(import\s+[\w.]*\b{m}\b|from\s+[\w.]*\b{m}\b\s+import|from\s+[\w.]+\s+import\s+[^\n]*\b{m}\b)")
        bad = [str(p.relative_to(root)) for p in _py_files(root, x["scope"])
               if p.stem != x["module"] and pat.search(_exec(p))]
        return None if not bad else f"{x['module']} is imported by {bad}"
    return f"unknown check {sorted(c)}"


def run_claims(root: Path, reg: dict) -> list:
    out = []
    for cl in reg["claims"]:
        if cl.get("kind") == "design":
            if not cl.get("reason"):
                out.append(f"{cl['id']}: a design claim must say why it needs no check")
            continue
        if not cl.get("checks"):
            out.append(f"{cl['id']}: a status claim with no check")
        for c in cl.get("checks", []):
            why = run_check(root, c)
            if why:
                out.append(f"{cl['id']}: {why}")
        text_there = (root / cl["where"]).exists() and cl["text"] in (root / cl["where"]).read_text()
        if not text_there:
            out.append(f"{cl['id']}: the claim text is no longer in {cl['where']} -- remove the entry")
    return out


def run_generated(root: Path, reg: dict) -> list:
    out = []
    for g in reg["generated"]:
        if not (root / g["generator"]).exists():
            out.append(f"{g['output']}: generator {g['generator']} does not exist")
        if g["verify"] == "reproduce" and not (root / g.get("test", "")).exists():
            out.append(f"{g['output']}: 'reproduce' needs a test that rebuilds it ({g.get('test')})")
        cc = g.get("count_claim")
        if cc:
            import importlib
            txt = (root / g["output"]).read_text()
            m = re.search(cc["regex"], txt)
            n = len(getattr(importlib.import_module(cc["module"]), cc["dict"]))
            if not m or int(m.group(1)) != n:
                out.append(f"{g['output']}: header count {m.group(1) if m else None} != {n} entries")
    return out


print("\nEVERY CLAIM IN THE REPO IS REGISTERED")
s = scan(ROOT, REG)
for x in s["generated"] + s["status"]:
    print("    UNREGISTERED", x)
check("no unregistered 'generated' claim", s["generated"], [])
check("no unregistered status claim", s["status"], [])

print("\nEVERY REGISTERED CLAIM HOLDS")
bad = run_claims(ROOT, REG) + run_generated(ROOT, REG)
for x in bad:
    print("    FAILS", x)
check("every claim's checks pass", bad, [])

print("\nTHE CHECKS BITE (planted trees)")
t = Path(tempfile.mkdtemp())
(t / "docs").mkdir()
(t / "deploy").mkdir()
(t / "pkg").mkdir()
(t / "deploy" / "crontab.box").write_text("# a comment -m pkg.job\n15 3 * * * python -m pkg.other\n")
(t / "docs" / "X.md").write_text("> **STATUS -- NOTHING HERE IS BUILT**\n")
(t / "pkg" / "a.py").write_text('"""Auto-generated by gen.py. Do not edit."""\nx = 1\n')
(t / "pkg" / "b.py").write_text("from pkg.a import x\nsecret_fn()\n")
empty = {"generated": [], "claims": []}
s = scan(t, empty)
check("an unregistered NOT BUILT banner is caught", any("docs/X.md" in x for x in s["status"]), True)
check("an unregistered 'Auto-generated' header is caught", any("pkg/a.py" in x for x in s["generated"]), True)
check("a cron claim only in a COMMENT does not count",
      run_check(t, {"cron": "-m pkg.job"}) is not None, True)
check("a job claimed stopped but still scheduled fails not_cron",
      run_check(t, {"not_cron": "-m pkg.other"}) is not None, True)
check("  and one only in a comment passes it", run_check(t, {"not_cron": "-m pkg.job"}), None)
check("a called symbol fails called_only_in",
      run_check(t, {"called_only_in": {"symbol": "secret_fn", "allowed": [], "scope": ["pkg"]}}) is not None, True)
check("an imported module fails not_imported",
      run_check(t, {"not_imported": {"module": "a", "scope": ["pkg"]}}) is not None, True)
check("a claim whose text left the file is flagged for removal",
      any("no longer in" in x for x in run_claims(t, {"claims": [{"id": "x", "where": "docs/X.md",
                                                                  "text": "IS BUILT AND RUNNING",
                                                                  "checks": [{"module_exists": "docs/X.md"}]}]})), True)

if failures:
    print(f"FAILED — {len(failures)}")
    for f in failures:
        print("  -", f)
    sys.exit(1)
print("PASSED — every status and 'generated' claim is registered, and every registered claim holds")
