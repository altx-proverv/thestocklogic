#!/usr/bin/env python3
"""
THE REGULATORY CONSTRAINT, MADE MECHANICAL.
===========================================

The Stock Logic is not registered with SEBI as a Research Analyst or an
Investment Adviser. A public page that tells a reader what to do is the single
thing that converts market data into regulated advice, so the constraint cannot
live in a style note that a future edit forgets. It is a test.

FAILS IF THE SERVED TEMPLATE CONTAINS, anywhere in copy, headings, tooltips,
alt text or aria labels: buy, sell, entry, target, stop loss, recommendation,
call, tip, or any grade or conviction label. Case-insensitive.

WHY THE WHOLE FILE AND NOT JUST THE MARKUP. Most of this page's copy is
generated by its own inline script -- the reading, the tape reasons, the stale
labels are all JS string literals. A test that scanned only the static markup
would pass a page whose every rendered sentence said "buy". So the scan covers
the file as served, which is what a reader's browser receives.

WORD BOUNDARIES, NOT SUBSTRINGS. "tooltip" is not "tip"; "recall" is not
"call"; "overbought" is not "buy". Substring matching would fail on words that
carry no instruction at all, and a test that cries wolf gets edited until it
stops failing, which is worse than no test.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

# ── WHAT THE RULE COVERS, AND WHAT IT CANNOT ──────────────────────
#
# EVERY PUBLICLY REACHABLE SERVED FILE, not just index.html. The gap this
# closes is real: manifest.json read "Daily NSE trade signals — SMC-based
# setups with entry, SL and targets", was served at /manifest.json, carried
# three forbidden words, and passed because the test looked at one file.
#
# THE SCOPE IS THE PUBLIC SURFACE, and that is a judgement worth stating
# rather than burying. §07 governs what TSL publishes to people who have not
# signed in. The member pages behind the login -- /dashboard, /atlas,
# /tsl-dashboard, /performance.html, /admin -- ARE a trade record: entry, stop
# and target columns are their entire purpose, and the operator kept them
# deliberately. Extending a forbidden-word test over them would leave two
# options, delete content that was explicitly preserved or weaken the test
# until it passes, and both are worse than naming the boundary here.
#
# So: everything an external visitor can reach is checked. Everything behind
# the gate is listed as out of scope, by name, so the boundary is visible and
# a new PUBLIC file cannot quietly land outside it.
# tape-vocabulary.json is EVERY SENTENCE THE TAPE CAN EMIT, in one file,
# which is the whole reason the phrases were moved out of the render code.
# It is listed here rather than with the gated pages on two grounds: it is
# anonymously fetchable at /tape-vocabulary.json like any other static file,
# and scanning it checks the tape's entire vocabulary in one pass instead of
# hoping a reviewer spots a bad phrase inside a template string. That is a
# STRICTER standard than the gated boundary below requires -- deliberately,
# because a phrase file is pure copy and has no columns to defend.
PUBLIC = ["index.html", "waitlist.html", "manifest.json",
          "tape-vocabulary.json"]

GATED_OUT_OF_SCOPE = ["home.html", "signals.html", "atlas.html",
                      "tsl-dashboard.html", "performance.html",
                      "admin.html", "flash.html"]

# Deployment config, not content. Served, but nobody reads it as copy.
CONFIG_NOT_CONTENT = ["vercel.json"]

SERVED = [ROOT / f for f in PUBLIC]

# Single words, matched on word boundaries. Exactly the operator's list --
# not a word more. "bullish" and "bearish" were in an earlier draft of this
# list and were removed: they are not on it, they describe an observation
# rather than instruct, and a test stricter than the rule it enforces gets
# argued with instead of obeyed.
FORBIDDEN_WORDS = ["buy", "sell", "entry", "target", "recommendation",
                   "call", "tip", "grade", "conviction"]

# Phrases, matched with flexible whitespace.
FORBIDDEN_PHRASES = ["stop loss", "stop-loss", "take profit", "price target",
                     "should buy", "should sell"]

# How this codebase has historically ENCODED a grade, rather than spelling it.
# signals.html carries ring-ap / ring-a / ring-b / ring-c classes; if one of
# those ever lands on a public page the label is back, spelled differently.
FORBIDDEN_TOKENS = ["ring-ap", "ring-a", "ring-b", "ring-c",
                    "grade-a", "grade-b", "grade-c", "A+ setup"]


# ── WHAT COUNTS AS COPY ───────────────────────────────────────────
#
# The rule names copy, headings, tooltips, alt text and aria labels. Raw-byte
# scanning fails that definition in both directions:
#
#   e.target.closest(...)     a DOM property. Not copy. Matched 'target'.
#   target="_blank"           an attribute NAME, and the external-source rule
#                             REQUIRES it. Matched 'target'.
#
# A test that flags those gets relaxed until it flags nothing. So the scan
# extracts the surfaces a reader actually sees: markup text nodes, the VALUES
# of the attributes that render as text, and every string literal in the
# inline script -- because this page generates most of its copy in JS, and a
# scan that skipped the script would pass a page whose every sentence said
# "buy".
TEXTUAL_ATTRS = ("title", "alt", "aria-label", "aria-description",
                 "aria-placeholder", "placeholder", "content", "aria-roledescription")


def _from_markup(frag: str) -> list:
    """Textual attribute VALUES plus text nodes, from any markup fragment."""
    out = []
    for attr in TEXTUAL_ATTRS:
        for m in re.finditer(attr + r"\s*=\s*(\"[^\"]*\"|'[^']*')", frag, re.I):
            out.append(m.group(1)[1:-1])
    out.append(re.sub(r"<[^>]+>", " ", frag))
    return out


def reader_visible(html: str) -> str:
    """Only what a reader can end up seeing: text nodes, textual attribute
    VALUES, and the copy inside JS string literals.

    JS LITERALS GET THE SAME TREATMENT AS MARKUP, because most of them ARE
    markup: this page builds its event cards with
    '<a href="..." target="_blank">'. Scanning that literal raw flagged the
    attribute NAME 'target' -- an attribute the external-source rule requires.
    Stripping tags inside the literal, and pulling its textual attribute
    values out first, treats generated markup exactly like static markup,
    which is what it becomes.
    """
    out = []
    scripts = re.findall(r"<script\b[^>]*>(.*?)</script>", html, re.S | re.I)
    markup = re.sub(r"<script\b[^>]*>.*?</script>", " ", html, flags=re.S | re.I)
    markup = re.sub(r"<style\b[^>]*>.*?</style>", " ", markup, flags=re.S | re.I)

    out += _from_markup(markup)

    for src in scripts:
        # COMMENTS ARE NOT COPY. A /* */ block in this page explains that the
        # external-source rule requires target="_blank" -- and the literal
        # inside that explanation was being read as a string and flagged.
        # Stripping block comments first is the same move as reading Python
        # through executable_source: judge the code, not the prose about it.
        # Line comments are only stripped at line start, so a URL inside a
        # string ("https://...") is never mangled.
        src = re.sub(r"/\*.*?\*/", " ", src, flags=re.S)
        src = re.sub(r"(?m)^\s*//.*$", " ", src)
        for m in re.finditer(r"'([^'\\\n]*)'|\"([^\"\\\n]*)\"", src):
            lit = m.group(1) if m.group(1) is not None else m.group(2)
            if lit:
                out += _from_markup(lit)

    return "\n".join(x for x in out if x)


# A DISCLAIMER IS NOT ADVICE. "Not a buy/sell recommendation" and "Not buy/sell
# advice" are REQUIRED disclosures, and flagging them would push a page toward
# removing its own disclaimer to pass a compliance test -- the exact opposite
# of the intent. A match is exempt when it sits inside a negation.
DISCLAIMER = re.compile(
    r"\bnot\s+(a\s+|an\s+)?(sebi[- ]registered\s+)?"
    r"[\w/&;, -]{0,40}$", re.I)


def _is_disclaimer(text: str, pos: int) -> bool:
    return bool(DISCLAIMER.search(text[max(0, pos - 60):pos]))


def hits(text: str) -> list:
    """Words and phrases are judged on what a READER SEES. The encoded-grade
    tokens are judged on the RAW file, because their whole point is that they
    do not appear as words: ring-ap is a class attribute, invisible to a copy
    scan and still a grade label on the page."""
    raw = text
    text = reader_visible(text) if "<" in text else text
    found = []
    for w in FORBIDDEN_WORDS:
        for m in re.finditer(r"\b" + re.escape(w) + r"\b", text, re.I):
            if _is_disclaimer(text, m.start()):
                continue
            found.append((w, m.start(), text[max(0, m.start() - 45):
                                             m.start() + 45]
                          .replace("\n", " ")))
    for p in FORBIDDEN_PHRASES:
        pat = re.escape(p).replace(r"\ ", r"\s+").replace(r"\-", r"[\s-]")
        for m in re.finditer(pat, text, re.I):
            found.append((p, m.start(), text[max(0, m.start() - 45):
                                             m.start() + 45]
                          .replace("\n", " ")))
    for t in FORBIDDEN_TOKENS:
        for m in re.finditer(r"\b" + re.escape(t) + r"\b", raw, re.I):
            found.append((t, m.start(), raw[max(0, m.start() - 45):
                                            m.start() + 45]
                          .replace("\n", " ")))
    return found


def main() -> int:
    ok = True

    print("EVERY PUBLICLY SERVED FILE")
    print("-" * 100)
    for page in SERVED:
        if not page.exists():
            print(f"  ** {page.name} IS MISSING **")
            ok = False
            continue
        txt = page.read_text(encoding="utf-8")
        found = hits(txt)
        ok &= not found
        print(f"  {page.name:<24}{len(txt):>8,} bytes   "
              f"{'clean' if not found else '** ' + str(len(found)) + ' HIT(S) **'}")
        for w, pos, ctx in found[:12]:
            print(f"      {w!r} at byte {pos}: …{ctx.strip()}…")

    print()
    print("THE PUBLIC SET IS COMPLETE")
    print("-" * 100)
    # Every served file is either checked or named out of scope. A new public
    # page that lands in neither list fails here rather than silently
    # escaping the rule.
    ignore = set()
    vi = ROOT / ".vercelignore"
    if vi.exists():
        for line in vi.read_text().splitlines():
            line = line.strip()
            if line and not line.startswith("#"):
                ignore.add(line.rstrip("/"))
    served_files = sorted(
        f.name for f in ROOT.iterdir()
        if f.is_file() and f.suffix in (".html", ".json", ".webmanifest")
        and f.name not in ignore and not f.name.endswith(".bak"))
    classified = set(PUBLIC) | set(GATED_OUT_OF_SCOPE) | set(CONFIG_NOT_CONTENT)
    unclassified = [f for f in served_files if f not in classified]
    good = not unclassified
    ok &= good
    print(f"  {'every served file is classified':<56}"
          f"{'ok' if good else '** UNCLASSIFIED: ' + ', '.join(unclassified) + ' **':<22}"
          f"{len(served_files)} served file(s)")
    print(f"      public  ({len(PUBLIC)}): {', '.join(PUBLIC)}")
    print(f"      gated   ({len(GATED_OUT_OF_SCOPE)}): "
          f"{', '.join(GATED_OUT_OF_SCOPE)}")

    print()
    print("AND THE TEST HAS TEETH — a planted word must fail it")
    print("-" * 100)
    # PROOF. Plant each forbidden word into a copy of the real page, in the
    # places the rule names, and assert every one is caught.
    # A SYNTHETIC PAGE CARRYING EVERY SURFACE THE RULE NAMES. These used to
    # plant into the real index.html by string anchor, which broke the moment
    # that page changed -- the plants silently reported "anchor not found"
    # instead of proving anything. A self-contained fixture cannot rot.
    def page(body, head=""):
        return ("<!DOCTYPE html><html><head>" + head +
                "</head><body>" + body +
                "<script>var x='harmless';</script></body></html>")

    plants = [
        ("visible copy",        page("<p>A clear buy here.</p>")),
        ("a heading",           page("<h2>Our top tip</h2>")),
        ("an aria-label",       page('<div aria-label="Entry and target levels">x</div>')),
        ("alt text",            page('<img src="/x.png" alt="recommendation chart">')),
        ("a title tooltip",     page('<span title="stop loss at 95">x</span>')),
        ("a meta description",  page("<p>ok</p>",
                                     head='<meta name="description" content="grade A setups">')),
        ("a JS string the page renders",
         "<!DOCTYPE html><html><body><script>"
         "var t='A strong conviction signal.';</script></body></html>"),
        ("an encoded grade class", page('<span class="ring-ap">x</span>')),
    ]
    for where, mutated in plants:
        found = hits(mutated)
        caught = bool(found)
        ok &= caught
        word = found[0][0] if found else "—"
        print(f"  planted in {where:<32}"
              f"{'CAUGHT ' + repr(word) if caught else '** MISSED **'}")

    print()
    print("AND IT DOES NOT CRY WOLF")
    print("-" * 100)
    # Words that CONTAIN a forbidden word but carry no instruction. If these
    # matched, the test would be edited until it stopped failing.
    for safe in ("tooltip", "recall", "overbought", "installation",
                 "upgraded", "entrypoint-free prose", "calibrate"):
        found = hits(safe)
        good = not found
        ok &= good
        print(f"  {safe:<34}{'ok — not a hit' if good else '** FALSE POSITIVE: ' + str(found[0][0]) + ' **'}")

    print("-" * 100)
    print("PAGE LANGUAGE:", "COMPLIANT" if ok else "*** VIOLATION ***")
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
