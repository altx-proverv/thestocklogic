SELECT
  (SELECT count(*) = 3 FROM information_schema.columns
     WHERE table_name = 'signals'
       AND column_name IN ('sector','sector_bias','sector_as_of'))        AS cols_added,
  (SELECT count(*) = 0 FROM public.signals WHERE sector IS NULL)          AS sector_backfilled,
  (SELECT count(*) > 0 FROM public.signals
     WHERE sector_as_of = 'backfill-2026-10-02')                          AS backfill_flagged,
  (SELECT count(*) = 0 FROM public.signal_outcomes WHERE sector = 'OTHER') AS other_cleared,
  (SELECT is_nullable = 'YES' FROM information_schema.columns
     WHERE table_name = 'signals' AND column_name = 'publication_kind')   AS pubkind_nullable,
  (SELECT count(*) = 0 FROM public.signals
     WHERE signal_date < DATE '2026-10-01'
       AND publication_kind IS NOT NULL)                                  AS history_nulled,
  (SELECT count(*) > 0 FROM public.signals
     WHERE signal_date >= DATE '2026-10-01'
       AND publication_kind = 'signal')                                   AS recent_kept,
  (SELECT col_description('public.signals'::regclass::oid, ordinal_position)
            LIKE 'DERIVED%' FROM information_schema.columns
     WHERE table_name = 'signals' AND column_name = 'score')              AS score_marked;
