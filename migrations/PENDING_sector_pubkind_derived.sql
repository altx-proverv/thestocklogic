-- sector_bias is deliberately NOT backfilled. It was the sector's momentum
-- classification ON THAT DATE, which sector_heatmap only covers from 2026-05
-- and which cannot be reconstructed before that. Left NULL rather than imputed:
-- a momentum reading invented three years later is not a weaker version of the
-- real thing, it is a different number wearing its name.

COMMENT ON COLUMN public.signals.sector IS
  'Sector from universe.SYMBOL_SECTOR_MAP. Read sector_as_of before using it: "recorded" means 06_push wrote it on the night of publication, "backfill-YYYY-MM-DD" means today''s map was applied retrospectively and a symbol reclassified since is attributed to its current sector.';

COMMENT ON COLUMN public.signals.sector_as_of IS
  'recorded = written at publication. backfill-YYYY-MM-DD = imputed on that date from the then-current sector map. Exists so an imputed sector can never be mistaken for an observed one, which is the mistake that made sector=OTHER invisible for seventeen months.';

COMMENT ON COLUMN public.signals.sector_bias IS
  'The sector''s momentum classification on the publication date (long/short/avoid). NULL on every row published before 2026-10-02 and not backfilled: it is a point-in-time reading that cannot be reconstructed, unlike the sector itself.';

