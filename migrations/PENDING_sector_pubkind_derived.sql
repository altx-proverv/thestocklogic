-- sector through on its next pass.
UPDATE public.signal_outcomes SET sector = NULL WHERE sector = 'OTHER';

COMMENT ON COLUMN public.signal_outcomes.sector IS
  'Copied from the signals row at resolution time. Was the constant "OTHER" on all 831 rows to 2026-10-02, because the resolvers read a column that did not exist with a default that hid it; those were set NULL and are repopulated as rows re-resolve.';

-- ─────────────────────────────────────────────────────────────────────
-- 2. publication_kind: A LABEL LEAK, made honest.
--
--    The column arrived as NOT NULL DEFAULT 'signal', so every row published
--    before it existed was backfilled to 'signal'. That makes the value
--    indistinguishable between "06_push published this as actionable" and
--    "this predates the column" -- and since the column was added the same
--    week the watchlist shipped, the value correlates with date rather than
--    with actionability. Anything learning from this table would be reading
--    a timestamp disguised as a categorical.
-- ─────────────────────────────────────────────────────────────────────

ALTER TABLE public.signals ALTER COLUMN publication_kind DROP NOT NULL;

UPDATE public.signals
   SET publication_kind = NULL
 WHERE signal_date < DATE '2026-10-01';

COMMENT ON COLUMN public.signals.publication_kind IS
  'signal = published as ATLAS-actionable. candidate = watchlist only, never entered. NULL = published before this column existed, so actionability was never recorded -- do NOT read NULL as either value. market_open tests `= ''signal''` positively, so a NULL row is watch-only rather than tradeable.';

-- ─────────────────────────────────────────────────────────────────────
-- 3. DERIVED FIELDS, marked rather than dropped.
--
--    Dropping them would break signals.html, which renders rr_1, rr_2 and
--    the sub-scores. What they need is to stop reading like independent
--    measurements: score equals the sum of the five sub-scores on all 845
--    rows that have them, mean gap 0.00, zero exceptions -- so testing the
--    six as separate features, which the last analysis did, was testing one
--    quantity six ways.
-- ─────────────────────────────────────────────────────────────────────

COMMENT ON COLUMN public.signals.score IS
  'DERIVED. Exactly the sum of score_regime + score_smc + score_technical + score_volume + score_rr -- verified on all 845 rows carrying sub-scores, mean gap 0.00. The six are one quantity and its decomposition, not six features. The score GATE was retired as non-predictive; this is kept for display and ranking.';

COMMENT ON COLUMN public.signals.score_smc IS
  'DERIVED component of score. See the comment on score: the five components sum to it exactly, so they are not independent of it or of each other.';
COMMENT ON COLUMN public.signals.score_regime IS 'DERIVED component of score. See score.';
COMMENT ON COLUMN public.signals.score_technical IS 'DERIVED component of score. See score.';
COMMENT ON COLUMN public.signals.score_volume IS 'DERIVED component of score. See score.';
COMMENT ON COLUMN public.signals.score_rr IS 'DERIVED component of score. See score.';

COMMENT ON COLUMN public.signals.rr_1 IS
  'CONSTANT 2.0 on every row, and rr_2 is constant 3.0. These are the fixed measurement yardstick the accuracy record is scored against (zone_entry.MEASURE_R1/R2), not a per-signal risk-reward -- ATLAS trades with no target at all. They carry no per-row information.';
COMMENT ON COLUMN public.signals.rr_2 IS 'CONSTANT 3.0. See rr_1.';

COMMENT ON COLUMN public.signals.sl_pct IS
